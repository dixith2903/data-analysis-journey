name = "Deekshith"

print(name[0:5]) # This will print the substring from index 0 to 4, which is "Deeks"

print(name[5:7]) # This will print the substring from index 5 to index 6, which is "hi"

print(name[1:-1]) # This will print the substring from index 1 to the second last character, which is "eekshith"