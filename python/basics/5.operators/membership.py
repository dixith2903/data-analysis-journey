# Membership Operators

# in operator checks if a value is present in a sequence (like a list, tuple, or string) and returns True if it is, otherwise False.

fruits = ["apple", "banana", "orange"]

print("apple" in fruits)  # True
print("grape" in fruits)  # False

# not in operator checks if a value is not present in a sequence and returns True if it is not, otherwise False.

numbers = [1, 2, 3, 4, 5]

print(3 not in numbers)  # False
print(6 not in numbers)  # True